type PanelProps = {
  doc: Doc;
  commit: (d: Doc, key?: string) => void;
  setContent: (p: Partial<BuilderContent>, key?: string) => void;
  setConstruction: (p: Partial<BuilderContent["construction"]>, key?: string) => void;
  setSketch: (s: Sketch, key?: string) => void;
  unit: DisplayUnit;
  selected: SketchHit | null;
  setSelected: (h: SketchHit | null) => void;
  selShape: SketchShape | null;
  deleteSelected: () => void;
  grid: number | null;
  setGrid: (g: number | null) => void;
  snapPts: boolean;
  setSnapPts: (v: boolean) => void;
  penMode: boolean;
  setPenMode: (v: boolean) => void;
  onTemplates: () => void;
  reference: ReactNode;
  artwork: ReactNode;
};

function BuilderPanel(p: PanelProps) {
  const { doc, unit } = p;
  const c = doc.content.construction;
  const sketch = doc.content.sketch;
  const method = METHODS.find((m) => m.value === c.method)!;
  const replaceShape = (s: SketchShape, key?: string) => p.setSketch({ ...sketch, shapes: sketch.shapes.map((x) => (x.id === s.id ? s : x)) }, key);
  const selDim = p.selected?.kind === "dim" ? sketch.dims.find((d) => d.id === p.selected!.id) : undefined;
  const selLabel = p.selected?.kind === "label" ? sketch.labels.find((l) => l.id === p.selected!.id) : undefined;

  return (
    <div className="divide-y">
      <PanelSection title="How it's built">
        <SelectField label="Method" value={c.method} options={METHODS.map((m) => ({ value: m.value, label: m.label }))} onChange={(method) => p.setConstruction({ method })} testId="builder-method" />
        <p className="-mt-1 text-[11px] text-muted-foreground">{method.hint}</p>
        {(c.method === "extrude" || c.method === "frame") && (
          <SelectField
            label="Drawing shows"
            value={sketch.plane}
            options={[
              { value: "front", label: "Front view (as you face it)" },
              { value: "top", label: "Plan (from above)" },
            ]}
            onChange={(plane) => p.setSketch({ ...sketch, plane })}
          />
        )}
        {c.method === "extrude" && <LengthField label={sketch.plane === "front" ? "Depth" : "Height"} valueMm={c.depth} unit={unit} min={1} onCommit={(depth) => p.setConstruction({ depth }, "depth")} testId="builder-depth" />}
        {c.method === "panel" && (
          <>
            <LengthField label="Thickness" valueMm={c.thickness} unit={unit} min={1} max={1000} onCommit={(thickness) => p.setConstruction({ thickness }, "thickness")} />
            <ToggleRow label="Feet" checked={c.feet} onChange={(feet) => p.setConstruction({ feet })} />
          </>
        )}
        {c.method === "flat" && <LengthField label="Thickness" valueMm={c.thickness} unit={unit} min={1} max={500} onCommit={(thickness) => p.setConstruction({ thickness }, "thickness")} />}
        {c.method === "frame" && (
          <>
            <div className="grid grid-cols-2 gap-3">
              <LengthField label="Beam size" valueMm={c.section} unit={unit} min={1} max={2000} onCommit={(section) => p.setConstruction({ section }, "section")} testId="builder-section" />
              <LengthField label={sketch.plane === "front" ? "Overall depth" : "Height"} valueMm={c.depth} unit={unit} allowZero onCommit={(depth) => p.setConstruction({ depth }, "depth")} hint={sketch.plane === "front" ? "0 = one flat frame" : undefined} />
            </div>
            <ToggleRow label="Round tube" checked={c.round} onChange={(round) => p.setConstruction({ round })} />
            <ToggleRow label="Panel infill" checked={c.infill} onChange={(infill) => p.setConstruction({ infill })} hint="Fills closed frames with a thin panel" />
          </>
        )}
        <Button variant="outline" className="h-11 w-full justify-start" onClick={p.onTemplates} data-testid="builder-templates">
          <LayoutTemplate className="mr-2 h-4 w-4" /> Exact size or example…
        </Button>
      </PanelSection>

      {p.reference}

      {c.method === "assembly" && <PartsEditor doc={doc} setContent={p.setContent} unit={unit} />}

      {(p.selShape || selDim || selLabel) && (
        <PanelSection
          title="Selected"
          action={
            <Button variant="ghost" size="sm" className="h-9 text-destructive" onClick={p.deleteSelected} aria-label="Delete the selected item">
              <Trash2 className="mr-1 h-4 w-4" /> Delete
            </Button>
          }
        >
          {p.selShape && <ShapeFields s={p.selShape} unit={unit} onChange={replaceShape} sketch={sketch} setSketch={p.setSketch} setSelected={p.setSelected} />}
          {selDim && (
            <>
              <p className="text-sm">
                Distance <span className="font-semibold tabular-nums">{formatLength(Math.hypot(selDim.b.x - selDim.a.x, selDim.b.y - selDim.a.y), unit)}</span>
              </p>
              <LengthField label="Offset from the line" valueMm={selDim.offset} unit={unit} allowZero min={-100000} onCommit={(offset) => p.setSketch({ ...sketch, dims: sketch.dims.map((d) => (d.id === selDim.id ? { ...d, offset } : d)) }, `dim:${selDim.id}`)} />
            </>
          )}
          {selLabel && <TextField label="Text" value={selLabel.text} maxLength={120} onCommit={(text) => p.setSketch({ ...sketch, labels: sketch.labels.map((l) => (l.id === selLabel.id ? { ...l, text } : l)) })} />}
        </PanelSection>
      )}

      <PanelSection title="Drawing aids">
        <div className="grid grid-cols-2 gap-3">
          <SelectField label="Snap to grid" value={String(p.grid ?? 0)} options={GRID_OPTIONS} onChange={(v) => p.setGrid(Number(v) || null)} />
          <div className="flex items-end">
            <ToggleRow label="Snap to points" checked={p.snapPts} onChange={p.setSnapPts} />
          </div>
        </div>
        <ToggleRow label="Pencil mode" checked={p.penMode} onChange={p.setPenMode} hint="Only the Pencil draws; fingers pan and zoom. Turns on when a Pencil is used." testId="builder-pen-mode" />
        <p className="text-[11px] text-muted-foreground">
          {sketch.shapes.length}/{CUSTOM_LIMITS.shapes} shapes. Snapping finds corners, centres and crossings of lines.
        </p>
      </PanelSection>

      {p.artwork}

      <PanelSection title="Details">
        <SelectField label="Category" value={(CUSTOM_CATEGORIES as readonly string[]).includes(doc.category) ? doc.category : "Other"} options={CUSTOM_CATEGORIES.map((x) => ({ value: x, label: x }))} onChange={(category) => p.commit({ ...doc, category })} />
        <TextField label="Description" value={doc.description} maxLength={400} multiline onCommit={(description) => p.commit({ ...doc, description })} placeholder="What it is, materials, notes for the crew" />
        <div className="grid grid-cols-2 gap-3">
          <ColorField label="Main colour" value={doc.color} onChange={(color) => p.commit({ ...doc, color }, "color")} />
          <ColorField label="Accent" value={doc.accentColor} onChange={(accentColor) => p.commit({ ...doc, accentColor }, "accent")} />
        </div>
      </PanelSection>
      <p className="px-4 py-3 text-[11px] text-muted-foreground">Models show size and placement only. They don't confirm that a structure is safe to build.</p>
    </div>
  );
}

function ShapeFields({ s, unit, onChange, sketch, setSketch, setSelected }: { s: SketchShape; unit: DisplayUnit; onChange: (s: SketchShape, key?: string) => void; sketch: Sketch; setSketch: (s: Sketch) => void; setSelected: (h: SketchHit | null) => void }) {
  const k = (f: string) => `shape:${s.id}:${f}`;
  const duplicate = () => {
    const copy: SketchShape =
      s.kind === "rect" ? { ...s, id: newSketchId(), x: s.x + 100, y: s.y } : s.kind === "circle" ? { ...s, id: newSketchId(), cx: s.cx + 100 } : { ...s, id: newSketchId(), points: s.points.map((q) => ({ x: q.x + 100, y: q.y })) };
    setSketch({ ...sketch, shapes: [...sketch.shapes, copy] });
    setSelected({ kind: "shape", id: copy.id });
  };
  const dupBtn = (
    <Button variant="outline" className="h-10 w-full justify-start" onClick={duplicate}>
      <Copy className="mr-2 h-4 w-4" /> Duplicate (100 mm to the right)
    </Button>
  );
  if (s.kind === "rect")
    return (
      <>
        <p className="text-xs text-muted-foreground">Rectangle</p>
        <div className="grid grid-cols-2 gap-3">
          <LengthField label="Width" valueMm={s.w} unit={unit} min={1} onCommit={(w) => onChange({ ...s, w }, k("w"))} testId="shape-width" />
          <LengthField label="Height" valueMm={s.h} unit={unit} min={1} onCommit={(h) => onChange({ ...s, h }, k("h"))} testId="shape-height" />
          <LengthField label="Left (X)" valueMm={s.x} unit={unit} allowZero min={-1e6} onCommit={(x) => onChange({ ...s, x }, k("x"))} />
          <LengthField label="Top (Y)" valueMm={s.y} unit={unit} allowZero min={-1e6} onCommit={(y) => onChange({ ...s, y }, k("y"))} />
        </div>
        {dupBtn}
      </>
    );
  if (s.kind === "circle")
    return (
      <>
        <p className="text-xs text-muted-foreground">Circle</p>
        <div className="grid grid-cols-2 gap-3">
          <LengthField label="Diameter" valueMm={s.r * 2} unit={unit} min={2} onCommit={(d) => onChange({ ...s, r: d / 2 }, k("r"))} testId="shape-diameter" />
          <span />
          <LengthField label="Centre X" valueMm={s.cx} unit={unit} allowZero min={-1e6} onCommit={(cx) => onChange({ ...s, cx }, k("cx"))} />
          <LengthField label="Centre Y" valueMm={s.cy} unit={unit} allowZero min={-1e6} onCommit={(cy) => onChange({ ...s, cy }, k("cy"))} />
        </div>
        {dupBtn}
      </>
    );
  const pts = s.points;
  const isLine = pts.length === 2 && !s.closed;
  const len = isLine ? Math.hypot(pts[1].x - pts[0].x, pts[1].y - pts[0].y) : 0;
  const ang = isLine ? (Math.atan2(-(pts[1].y - pts[0].y), pts[1].x - pts[0].x) * 180) / Math.PI : 0;
  const setLine = (L: number, deg: number) => {
    const a = (deg * Math.PI) / 180;
    onChange({ ...s, points: [pts[0], { x: Math.round((pts[0].x + Math.cos(a) * L) * 10) / 10, y: Math.round((pts[0].y - Math.sin(a) * L) * 10) / 10 }] }, k("line"));
  };
  return (
    <>
      <p className="text-xs text-muted-foreground">
        {isLine ? "Line" : s.closed ? "Closed shape" : "Open line"} · {pts.length} points · {formatLength(polyLength(pts, s.closed), unit)} long
      </p>
      {isLine && (
        <div className="grid grid-cols-2 gap-3">
          <LengthField label="Length" valueMm={len} unit={unit} min={1} onCommit={(L) => setLine(L, ang)} testId="line-length" />
          <NumberField label="Angle" suffix="°" value={Math.round(ang * 10) / 10} min={-360} max={360} step={0.5} onCommit={(d) => setLine(len, d)} />
        </div>
      )}
      {pts.length >= 3 && <ToggleRow label="Closed shape" checked={s.closed} onChange={(closed) => onChange({ ...s, closed })} hint="Needed for extrude, panel and flat outline" />}
      {pts.length <= 24 ? (
        <details className="rounded-lg border px-3 py-2" open={pts.length <= 6}>
          <summary className="min-h-9 cursor-pointer py-1 text-sm font-medium">Exact points</summary>
          <div className="mt-2 space-y-2">
            {pts.map((q, i) => (
              <div key={i} className="grid grid-cols-[1.5rem_1fr_1fr] items-end gap-2">
                <span className="pb-3 text-xs text-muted-foreground">{i + 1}</span>
                <LengthField label="X" valueMm={q.x} unit={unit} allowZero min={-1e6} onCommit={(x) => onChange({ ...s, points: pts.map((pp, j) => (j === i ? { ...pp, x } : pp)) }, k(`p${i}x`))} />
                <LengthField label="Y" valueMm={q.y} unit={unit} allowZero min={-1e6} onCommit={(y) => onChange({ ...s, points: pts.map((pp, j) => (j === i ? { ...pp, y } : pp)) }, k(`p${i}y`))} />
              </div>
            ))}
          </div>
        </details>
      ) : (
        <p className="text-[11px] text-muted-foreground">Freehand strokes have many points; use Clean up on the drawing to simplify, then type exact values.</p>
      )}
      {dupBtn}
    </>
  );
}

function PartsEditor({ doc, setContent, unit }: { doc: Doc; setContent: (p: Partial<BuilderContent>, key?: string) => void; unit: DisplayUnit }) {
  const parts = doc.content.parts;
  const [open, setOpen] = useState<string | null>(parts[0]?.id ?? null);
  // Editing a part by hand detaches it from the template so a resize keeps the edit.
  const setParts = (next: CustomPart[], key?: string) => setContent({ parts: next, template: null }, key);
  const setPart = (id: string, patch: Partial<CustomPart>, key: string) => setParts(parts.map((q) => (q.id === id ? { ...q, ...patch } : q)), `part:${id}:${key}`);
  const add = (shape: "box" | "cylinder") => {
    const id = newSketchId("p");
    setParts([...parts, { id, name: `Part ${parts.length + 1}`, shape, x: 0, y: 0, z: 0, w: 500, h: 500, d: 500, tone: "body", color: null }]);
    setOpen(id);
  };
  const fromDrawing = () => {
    const depth = doc.content.construction.depth || 100;
    const extra = rectsToParts(doc.content.sketch, depth, parts.length + 1);
    if (extra.length) setParts([...parts, ...extra]);
  };
  const rects = doc.content.sketch.shapes.filter((s) => s.kind === "rect").length;
  return (
    <PanelSection title={`Parts (${parts.length}/${CUSTOM_LIMITS.parts})`}>
      {doc.content.template && <p className="text-[11px] text-muted-foreground">Made from the {doc.content.template.id.replace("_", " ")} template: resizing the placed object regenerates the parts exactly. Editing a part here keeps your change instead.</p>}
      <p className="text-[11px] text-muted-foreground">Positions are from the object's centre: X across, Y up from the floor (the part's base), Z towards the front.</p>
      <ul className="space-y-2">
        {parts.map((q, i) => (
          <li key={q.id} className="rounded-lg border">
            <button type="button" className="flex min-h-11 w-full items-center gap-2 px-3 text-left text-sm" onClick={() => setOpen(open === q.id ? null : q.id)} aria-expanded={open === q.id}>
              <span className="h-3 w-3 shrink-0 rounded-sm border" style={{ background: q.color ?? (q.tone === "body" ? doc.color : q.tone === "accent" ? doc.accentColor : undefined) }} />
              <span className="min-w-0 flex-1 truncate font-medium">{q.name || `Part ${i + 1}`}</span>
              <span className="shrink-0 text-[11px] tabular-nums text-muted-foreground">
                {q.shape === "cylinder" ? `⌀${formatLength(q.w, unit)}` : `${formatLength(q.w, unit)}×${formatLength(q.d, unit)}`} × {formatLength(q.h, unit)}
              </span>
            </button>
            {open === q.id && (
              <div className="space-y-3 border-t p-3">
                <TextField label="Name" value={q.name} maxLength={80} onCommit={(name) => setPart(q.id, { name }, "name")} />
                <div className="grid grid-cols-2 gap-3">
                  <SelectField label="Shape" value={q.shape} options={[{ value: "box", label: "Box" }, { value: "cylinder", label: "Cylinder" }]} onChange={(shape) => setPart(q.id, { shape }, "shape")} />
                  <SelectField label="Finish" value={q.tone} options={PART_TONES.map((t) => ({ value: t, label: TONE_LABEL[t] }))} onChange={(tone) => setPart(q.id, { tone }, "tone")} />
                  <LengthField label={q.shape === "cylinder" ? "Diameter" : "Width (X)"} valueMm={q.w} unit={unit} min={1} onCommit={(w) => setPart(q.id, { w }, "w")} />
                  {q.shape === "box" ? <LengthField label="Depth (Z)" valueMm={q.d} unit={unit} min={1} onCommit={(d) => setPart(q.id, { d }, "d")} /> : <span />}
                  <LengthField label="Height" valueMm={q.h} unit={unit} min={1} onCommit={(h) => setPart(q.id, { h }, "h")} />
                  <LengthField label="Base above floor" valueMm={q.y} unit={unit} allowZero onCommit={(y) => setPart(q.id, { y }, "y")} />
                  <LengthField label="Across (X)" valueMm={q.x} unit={unit} allowZero min={-1e6} onCommit={(x) => setPart(q.id, { x }, "x")} />
                  <LengthField label="Front/back (Z)" valueMm={q.z} unit={unit} allowZero min={-1e6} onCommit={(z) => setPart(q.id, { z }, "z")} />
                </div>
                <div className="flex gap-2">
                  <Button
                    variant="outline"
                    className="h-10 flex-1"
                    onClick={() => {
                      const id = newSketchId("p");
                      setParts([...parts, { ...q, id, name: `${q.name} copy`, x: q.x + q.w }]);
                      setOpen(id);
                    }}
                    disabled={parts.length >= CUSTOM_LIMITS.parts}
                  >
                    <Copy className="mr-1 h-4 w-4" /> Duplicate
                  </Button>
                  <Button variant="outline" className="h-10 flex-1 text-destructive" onClick={() => setParts(parts.filter((x) => x.id !== q.id))}>
                    <Trash2 className="mr-1 h-4 w-4" /> Remove
                  </Button>
                </div>
              </div>
            )}
          </li>
        ))}
      </ul>
      <div className="grid grid-cols-2 gap-2">
        <Button variant="outline" className="h-11" onClick={() => add("box")} disabled={parts.length >= CUSTOM_LIMITS.parts} data-testid="add-part-box">
          <Plus className="mr-1 h-4 w-4" /> Box
        </Button>
        <Button variant="outline" className="h-11" onClick={() => add("cylinder")} disabled={parts.length >= CUSTOM_LIMITS.parts}>
          <Plus className="mr-1 h-4 w-4" /> Cylinder
        </Button>
      </div>
      {rects > 0 && (
        <Button variant="outline" className="h-11 w-full justify-start" onClick={fromDrawing}>
          <PenTool className="mr-2 h-4 w-4" /> Add the {rects} drawn rectangle{rects === 1 ? "" : "s"} as parts
        </Button>
      )}
    </PanelSection>
  );
}

