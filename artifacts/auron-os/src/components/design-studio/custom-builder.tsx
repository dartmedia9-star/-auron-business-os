function TemplateDialog({ open, onOpenChange, unit, onApply }: { open: boolean; onOpenChange: (v: boolean) => void; unit: DisplayUnit; onApply: (content: BuilderContent, meta?: Partial<Doc>) => void }) {
  const [picked, setPicked] = useState<TemplateDef | null>(null);
  const [values, setValues] = useState<Record<string, number | boolean>>({});
  useEffect(() => {
    if (!open) setPicked(null);
  }, [open]);
  const pick = (t: TemplateDef) => {
    setPicked(t);
    setValues(Object.fromEntries(t.params.map((q) => [q.key, q.default])));
  };
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-h-[90dvh] overflow-y-auto sm:max-w-lg" data-testid="template-dialog">
        <DialogHeader>
          <DialogTitle>{picked ? picked.label : "Exact size or example"}</DialogTitle>
          <DialogDescription>{picked ? picked.description : "Type exact sizes for a common shape, or start from a worked example. This replaces the current drawing; you can undo it."}</DialogDescription>
        </DialogHeader>
        {!picked ? (
          <div className="space-y-4">
            <section>
              <h3 className="mb-2 text-eyebrow font-semibold uppercase text-muted-foreground">Type the sizes</h3>
              <div className="grid grid-cols-2 gap-2">
                {TEMPLATES.map((t) => (
                  <button key={t.id} type="button" className="min-h-16 rounded-lg border p-2.5 text-left hover:bg-muted" onClick={() => pick(t)} data-template={t.id}>
                    <span className="block text-sm font-medium">{t.label}</span>
                    <span className="mt-0.5 block text-[11px] leading-snug text-muted-foreground">{t.description}</span>
                  </button>
                ))}
              </div>
            </section>
            <section>
              <h3 className="mb-2 text-eyebrow font-semibold uppercase text-muted-foreground">Examples</h3>
              <div className="grid grid-cols-2 gap-2">
                {EXAMPLES.map((x) => (
                  <button
                    key={x.id}
                    type="button"
                    className="min-h-16 rounded-lg border p-2.5 text-left hover:bg-muted"
                    onClick={() => {
                      onApply(x.content(), { name: x.label, color: x.color, accentColor: x.accentColor });
                      onOpenChange(false);
                    }}
                    data-example={x.id}
                  >
                    <span className="block text-sm font-medium">{x.label}</span>
                    <span className="mt-0.5 block text-[11px] leading-snug text-muted-foreground">{x.description}</span>
                  </button>
                ))}
              </div>
            </section>
          </div>
        ) : (
          <form
            className="space-y-3"
            onSubmit={(e) => {
              e.preventDefault();
              onApply(applyTemplate(picked.id as TemplateId, values), { name: picked.label });
              onOpenChange(false);
            }}
          >
            <div className="grid grid-cols-2 gap-3">
              {picked.params.map((q) => {
                const v = values[q.key] ?? q.default;
                if (q.kind === "boolean") return <ToggleRow key={q.key} label={q.label} checked={Boolean(v)} onChange={(b) => setValues({ ...values, [q.key]: b })} />;
                if (q.kind === "count") return <NumberField key={q.key} label={q.label} value={Number(v)} min={q.min} max={q.max} onCommit={(n) => setValues({ ...values, [q.key]: n })} />;
                return <LengthField key={q.key} label={q.label} valueMm={Number(v)} unit={unit} min={q.min ?? 0} max={q.max} allowZero={(q.min ?? 1) === 0} onCommit={(n) => setValues({ ...values, [q.key]: n })} testId={`template-${q.key}`} />;
              })}
            </div>
            <DialogFooter className="gap-2">
              <Button type="button" variant="outline" className="h-11" onClick={() => setPicked(null)}>
                Back
              </Button>
              <Button type="submit" className="h-11" data-testid="template-apply">
                Use these sizes
              </Button>
            </DialogFooter>
          </form>
        )}
      </DialogContent>
    </Dialog>
  );
}

function TextDialog({ at, onClose, onSave }: { at: SketchPoint | null; onClose: () => void; onSave: (text: string) => void }) {
  const [text, setText] = useState("");
  useEffect(() => setText(""), [at]);
  return (
    <Dialog open={!!at} onOpenChange={(v) => !v && onClose()}>
      <DialogContent>
        <form
          onSubmit={(e) => {
            e.preventDefault();
            if (text.trim()) onSave(text.trim().slice(0, 120));
          }}
        >
          <DialogHeader>
            <DialogTitle>Add a note</DialogTitle>
            <DialogDescription>Notes stay on the drawing and don't change the 3D shape.</DialogDescription>
          </DialogHeader>
          <div className="my-4 space-y-1.5">
            <Label htmlFor="builder-text">Text</Label>
            <Input id="builder-text" className="h-11 text-base" value={text} maxLength={120} onChange={(e) => setText(e.target.value)} autoFocus />
          </div>
          <DialogFooter>
            <Button type="button" variant="outline" className="h-11" onClick={onClose}>
              Cancel
            </Button>
            <Button type="submit" className="h-11" disabled={!text.trim()}>
              Add
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
