function initialDoc(req: BuilderRequest): { doc: Doc; problem: string | null } {
  const base = { category: "Other", description: "", color: "#d7d2c8", accentColor: "#c8a24a" };
  if (req.kind === "new") {
    if (req.template) {
      const t = TEMPLATES.find((x) => x.id === req.template)!;
      return { doc: { ...base, name: t.label, content: applyTemplate(t.id, {}) }, problem: null };
    }
    return { doc: { ...base, name: "New custom object", content: emptyContent() }, problem: null };
  }
  if (req.kind === "instance") return { doc: { ...base, name: req.name, color: req.color, accentColor: req.accentColor, finishes: req.finishes, content: specToContent(req.spec) }, problem: null };
  const r = parseCustomDefinition(req.item.definition);
  if (!r.ok) return { doc: { ...base, name: req.item.name, category: req.item.category, description: req.item.description ?? "", content: emptyContent() }, problem: `The saved drawing couldn't be read (${r.error}). You can redraw it and save to repair it.` };
  const d = r.definition;
  return {
    doc: {
      name: req.item.name,
      category: req.item.category,
      description: req.item.description ?? "",
      color: d.color,
      accentColor: d.accentColor,
      finishes: d.finishes,
      content: { sketch: d.sketch, construction: d.construction, parts: d.parts, template: d.template },
    },
    problem: null,
  };
}

function useWide() {
  const q = "(min-width: 1024px)";
  const [m, setM] = useState(() => typeof window !== "undefined" && window.matchMedia(q).matches);
  useEffect(() => {
    const mql = window.matchMedia(q);
    const on = () => setM(mql.matches);
    mql.addEventListener("change", on);
    return () => mql.removeEventListener("change", on);
  }, []);
  return m;
}

export type CustomBuilderProps = {
  request: BuilderRequest;
  onClose: () => void;
  unit?: DisplayUnit;
  /** In the editor: put the object into the current design (an independent copy). */
  onPlace?: (placement: CustomPlacement) => void;
  /** In the editor, for an instance: replace that object's recipe only. */
  onApplyInstance?: (objectId: string, change: { spec: CustomSpec; color: string; accentColor: string; name: string; finishes?: Finishes }) => void;
};

export default function CustomBuilder({ request, onClose, unit: unitProp, onPlace, onApplyInstance }: CustomBuilderProps) {
  // Starts in the design's unit (or the device default); switching here only changes how lengths are shown.
  const [unit, setUnit] = useState<DisplayUnit>(() => unitProp ?? getDefaultUnit());
  const { toast } = useToast();
  const qc = useQueryClient();
  const wide = useWide();
  const init = useMemo(() => initialDoc(request), [request]);
  const [history, setHistory] = useState<History<Doc>>(() => createHistory(init.doc));
  const doc = history.present;
  const [saved, setSaved] = useState<LibraryObject | null>(request.kind === "library" ? request.item : null);
  const savedDoc = useRef<Doc | null>(request.kind === "new" ? null : init.doc);
  const [problem, setProblem] = useState(init.problem);
  const [tool, setTool] = useState<BuilderTool>(request.kind === "new" && !request.template ? "rect" : "select");
  const [selected, setSelected] = useState<SketchHit | null>(null);
  const [grid, setGrid] = useState<number | null>(50);
  const [snapPts, setSnapPts] = useState(true);
  const [penMode, setPenMode] = useState(false);
  const [pane, setPane] = useState<"draw" | "3d">("draw");
  const [panelOpen, setPanelOpen] = useState(true);
  const [draftState, setDraftState] = useState<{ active: boolean; points: number; tool: BuilderTool | null }>({ active: false, points: 0, tool: null });
  const [templateOpen, setTemplateOpen] = useState(false);
  const [textAt, setTextAt] = useState<SketchPoint | null>(null);
  const [confirmClose, setConfirmClose] = useState(false);
  const [fitKey, setFitKey] = useState(0);
  const [restore, setRestore] = useState<{ doc: Doc; at: number } | null>(null);
  const canvas = useRef<BuilderCanvasHandle>(null);
  const [refMode, setRefModeState] = useState<RefMode>(null);
  const [calPoints, setCalPoints] = useState<SketchPoint[]>([]);
  const setRefMode = (m: RefMode) => {
    setRefModeState(m);
    setCalPoints([]);
  };
  const create = useCreateDesignObject();
  const update = useUpdateDesignObject();
  const dark = typeof document !== "undefined" && document.documentElement.classList.contains("dark");

  const commit = useCallback((next: Doc, key?: string) => setHistory((h) => pushHistory(h, next, key ? { key } : {})), []);
  const setContent = (patch: Partial<BuilderContent>, key?: string) => commit({ ...doc, content: { ...doc.content, ...patch } }, key);
  const setSketch = (sketch: Sketch, key?: string) => setContent({ sketch }, key);
  const setConstruction = (patch: Partial<BuilderContent["construction"]>, key?: string) => setContent({ construction: { ...doc.content.construction, ...patch } }, key);

  // Validated recipe; the preview keeps showing the last good one while the drawing is unfinished.
  const result = useMemo(() => buildSpec(doc.content), [doc.content]);
  const lastGood = useRef<{ spec: CustomSpec; parts: ReturnType<typeof customParts> } | null>(null);
  const current = useMemo(() => {
    if (!result.ok) return null;
    try {
      return { spec: result.spec, parts: customParts(result.spec) };
    } catch {
      return null;
    }
  }, [result]);
  if (current) lastGood.current = current;
  const shown = current ?? lastGood.current;
  const size = shown ? customSize(shown.spec) : null;
  const dirty = savedDoc.current === null ? history.past.length > 0 : savedDoc.current !== doc;

  // Unsaved new drawings survive a reload of the page (local to this browser only).
  useEffect(() => {
    if (request.kind !== "new") return;
    try {
      const raw = window.localStorage.getItem(DRAFT_KEY);
      if (raw) {
        const v = JSON.parse(raw) as { doc: Doc; at: number };
        if (v?.doc?.content?.sketch && typeof v.at === "number") setRestore(v);
      }
    } catch {
      /* ignore */
    }
  }, [request]);
  useEffect(() => {
    if (request.kind !== "new" || saved || !dirty) return;
    const t = window.setTimeout(() => {
      try {
        window.localStorage.setItem(DRAFT_KEY, JSON.stringify({ doc, at: Date.now() }));
      } catch {
        /* storage unavailable: nothing to restore later */
      }
    }, 600);
    return () => window.clearTimeout(t);
  }, [doc, dirty, saved, request]);
  const clearDraft = () => {
    try {
      window.localStorage.removeItem(DRAFT_KEY);
    } catch {
      /* ignore */
    }
  };

  const undo = () => setHistory((h) => historyUndo(h));
  const redo = () => setHistory((h) => historyRedo(h));
  const selShape = selected?.kind === "shape" ? doc.content.sketch.shapes.find((s) => s.id === selected.id) ?? null : null;

  const deleteSelected = () => {
    if (!selected) return;
    const s = doc.content.sketch;
    setSketch({ ...s, shapes: s.shapes.filter((x) => x.id !== selected.id), dims: s.dims.filter((x) => x.id !== selected.id), labels: s.labels.filter((x) => x.id !== selected.id) });
    setSelected(null);
  };

  // Keyboard: tool letters, undo/redo, delete, Enter / Escape for multi-tap tools.
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const t = e.target as HTMLElement;
      if (t.closest("input, textarea, select, [contenteditable=true]")) return;
      // Another dialog or menu is open on top of the builder.
      if (document.querySelectorAll("[role=dialog], [role=alertdialog]").length > 1 || document.querySelector("[role=menu], [role=listbox]")) return;
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "z") {
        e.preventDefault();
        if (e.shiftKey) redo();
        else undo();
        return;
      }
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "y") {
        e.preventDefault();
        redo();
        return;
      }
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      if (e.key === "Escape") {
        if (draftState.active) canvas.current?.cancel();
        else setSelected(null);
        return;
      }
      if (e.key === "Enter" && draftState.active) {
        canvas.current?.finish();
        return;
      }
      if ((e.key === "Delete" || e.key === "Backspace") && selected) {
        e.preventDefault();
        deleteSelected();
        return;
      }
      const hit = TOOLS.find((x) => x.key === e.key.toUpperCase());
      if (hit) setTool(hit.tool);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  });

  const definition = () => {
    if (!result.ok) return null;
    const c = doc.content;
    const finishes = doc.finishes && Object.keys(doc.finishes).length ? doc.finishes : undefined;
    const d = { v: 1 as const, sketch: c.sketch, construction: c.construction, parts: c.parts, template: c.template, spec: result.spec, color: doc.color, accentColor: doc.accentColor, elevation: 0, ...(finishes ? { finishes } : {}) };
    const parsed = parseCustomDefinition(d);
    if (!parsed.ok) {
      toast({ title: "This object can't be saved yet", description: parsed.error, variant: "destructive" });
      return null;
    }
    return parsed.definition;
  };
  const name = doc.name.trim().slice(0, 120) || "Custom object";

  const saveNew = () => {
    const def = definition();
    if (!def) return;
    create.mutate(
      { data: { name, category: doc.category, description: doc.description.trim() || null, definition: def } },
      {
        onSuccess: (item) => {
          setSaved(item);
          savedDoc.current = doc;
          clearDraft();
          void qc.invalidateQueries({ queryKey: getListDesignObjectsQueryKey() });
          toast({ title: "Saved to My Custom Objects", description: item.name });
        },
        onError: (err) => toast({ title: "Couldn't save", description: plainError(err), variant: "destructive" }),
      },
    );
  };
  const saveExisting = () => {
    if (!saved) return saveNew();
    const def = definition();
    if (!def) return;
    update.mutate(
      { id: saved.id, data: { baseRevision: saved.revision, name, category: doc.category, description: doc.description.trim() || null, definition: def } },
      {
        onSuccess: (item) => {
          setSaved(item);
          savedDoc.current = doc;
          setProblem(null);
          void qc.invalidateQueries({ queryKey: getListDesignObjectsQueryKey() });
          toast({ title: "Custom object saved", description: "New placements use this version. Objects already placed keep their own copy." });
        },
        onError: (err) => {
          const conflict = (err as { status?: number }).status === 409;
          toast({
            title: conflict ? "Someone else saved this object first" : "Couldn't save",
            description: conflict ? "Your drawing is still here. Use “Save as new” to keep it as a separate object." : plainError(err),
            variant: "destructive",
          });
        },
      },
    );
  };
  const applyInstance = () => {
    if (request.kind !== "instance" || !onApplyInstance || !result.ok) return;
    onApplyInstance(request.objectId, { spec: result.spec, color: doc.color, accentColor: doc.accentColor, name, finishes: doc.finishes && Object.keys(doc.finishes).length ? doc.finishes : undefined });
    savedDoc.current = doc;
    onClose();
  };
  const place = () => {
    if (!onPlace || !result.ok) return;
    onPlace({ spec: result.spec, name, color: doc.color, accentColor: doc.accentColor, elevation: 0, libraryId: saved?.id ?? null, libraryRevision: saved?.revision ?? null, finishes: doc.finishes });
    onClose();
  };
  const tryClose = () => (dirty ? setConfirmClose(true) : onClose());
  const busy = create.isPending || update.isPending;

  const cleanup = (square: boolean) => {
    if (!selShape || selShape.kind !== "poly") return;
    const size = polyLength(selShape.points, selShape.closed);
    const r = cleanupStroke(selShape.points, { tolerance: Math.max(2, size / 150), squareAngles: square, closeGap: Math.max(20, size / 25), grid: grid ?? undefined });
    if (r.points.length < 2) return;
    const s = doc.content.sketch;
    setSketch({ ...s, shapes: s.shapes.map((x) => (x.id === selShape.id ? { ...selShape, points: r.points, closed: selShape.closed || r.closed } : x)) });
    toast({ title: "Stroke cleaned up", description: `${selShape.points.length} points → ${r.points.length}${r.closed && !selShape.closed ? ", closed" : ""}. Undo to go back.` });
  };

  const header = (
    <div className="flex h-14 shrink-0 items-center gap-2 border-b bg-card px-2 sm:px-3">
      <Button variant="ghost" size="icon" className="h-11 w-11 shrink-0" onClick={tryClose} aria-label="Close the Custom Builder" data-testid="builder-close">
        <X className="h-5 w-5" />
      </Button>
      <div className="min-w-0 flex-1">
        <Input value={doc.name} onChange={(e) => commit({ ...doc, name: e.target.value.slice(0, 120) }, "name")} className="h-10 max-w-xs border-transparent bg-transparent px-2 text-base font-semibold shadow-none focus-visible:border-input" aria-label="Object name" data-testid="builder-name" />
      </div>
      <Button variant="ghost" size="icon" className="h-11 w-11 shrink-0" onClick={undo} disabled={!history.past.length} aria-label="Undo" title="Undo (Ctrl+Z)">
        <Undo2 className="h-5 w-5" />
      </Button>
      <Button variant="ghost" size="icon" className="h-11 w-11 shrink-0" onClick={redo} disabled={!history.future.length} aria-label="Redo" title="Redo (Ctrl+Shift+Z)">
        <Redo2 className="h-5 w-5" />
      </Button>
      <DropdownMenu>
        <DropdownMenuTrigger asChild>
          <Button variant="outline" size="icon" className="h-11 w-11 shrink-0" aria-label="More builder actions">
            <MoreHorizontal className="h-5 w-5" />
          </Button>
        </DropdownMenuTrigger>
        <DropdownMenuContent align="end" className="w-60">
          <DropdownMenuLabel>Show lengths in</DropdownMenuLabel>
          <DropdownMenuRadioGroup value={unit} onValueChange={(v) => setUnit(v as DisplayUnit)}>
            {DISPLAY_UNITS.map((u) => (
              <DropdownMenuRadioItem key={u} value={u} className="min-h-10" data-testid={`builder-unit-${u}`}>
                {UNIT_LABELS[u]}
              </DropdownMenuRadioItem>
            ))}
          </DropdownMenuRadioGroup>
          <DropdownMenuSeparator />
          <DropdownMenuItem className="min-h-11" onSelect={() => setTemplateOpen(true)}>
            <LayoutTemplate className="mr-2 h-4 w-4" /> Exact size or example…
          </DropdownMenuItem>
          {request.kind !== "instance" && saved && (
            <DropdownMenuItem className="min-h-11" onSelect={saveNew} disabled={!result.ok || busy}>
              <Copy className="mr-2 h-4 w-4" /> Save as new custom object
            </DropdownMenuItem>
          )}
          {request.kind === "instance" && (
            <DropdownMenuItem className="min-h-11" onSelect={saveNew} disabled={!result.ok || busy}>
              <Copy className="mr-2 h-4 w-4" /> Save to My Custom Objects
            </DropdownMenuItem>
          )}
          {onPlace && request.kind !== "instance" && (
            <DropdownMenuItem className="min-h-11" onSelect={place} disabled={!result.ok} data-testid="builder-place">
              <Plus className="mr-2 h-4 w-4" /> Place in this design
            </DropdownMenuItem>
          )}
          <DropdownMenuSeparator />
          <DropdownMenuItem
            className="min-h-11 text-destructive focus:text-destructive"
            onSelect={() => {
              setSketch({ ...doc.content.sketch, shapes: [], dims: [], labels: [] });
              setSelected(null);
            }}
          >
            <Trash2 className="mr-2 h-4 w-4" /> Clear the drawing
          </DropdownMenuItem>
        </DropdownMenuContent>
      </DropdownMenu>
      {request.kind === "instance" ? (
        <Button className="h-11 shrink-0" onClick={applyInstance} disabled={!result.ok} data-testid="builder-apply">
          <Check className="mr-1.5 h-4 w-4" /> Apply<span className="hidden sm:inline">&nbsp;to this object</span>
        </Button>
      ) : (
        <Button className="h-11 shrink-0" onClick={saved ? saveExisting : saveNew} disabled={!result.ok || busy || (!!saved && !dirty)} data-testid="builder-save">
          <Check className="mr-1.5 h-4 w-4" /> {saved ? (dirty ? "Save" : "Saved") : "Save"}
        </Button>
      )}
    </div>
  );

  const toolButtons = (vertical: boolean) => (
    <div className={cn("flex shrink-0 gap-1", vertical ? "flex-col overflow-y-auto border-r bg-card px-1.5 py-2" : "overflow-x-auto border-b bg-card px-2 py-1.5 [scrollbar-width:none]")} role="toolbar" aria-label="Drawing tools" aria-orientation={vertical ? "vertical" : "horizontal"}>
      {TOOLS.map((t, i) => {
        const sep = i > 0 && TOOLS[i - 1].group !== t.group;
        const Icon = t.icon;
        return (
          <div key={t.tool} className={cn("flex", vertical ? "flex-col" : "flex-row", sep && (vertical ? "mt-1.5 border-t pt-1.5" : "ml-1.5 border-l pl-1.5"))}>
            <button
              type="button"
              className={cn("flex h-11 w-11 shrink-0 items-center justify-center rounded-lg", tool === t.tool ? "bg-primary text-primary-foreground" : "text-foreground hover:bg-muted")}
              onClick={() => setTool(t.tool)}
              aria-pressed={tool === t.tool}
              aria-label={`${t.label} (${t.key})`}
              title={`${t.label} (${t.key})`}
              data-builder-tool={t.tool}
            >
              <Icon className="h-5 w-5" />
            </button>
          </div>
        );
      })}
    </div>
  );

  const contextStrip = (
    <div className="pointer-events-none absolute inset-x-2 top-2 flex flex-wrap items-start gap-2">
      <div className="pointer-events-auto max-w-full rounded-lg border bg-card/95 px-3 py-1.5 text-xs text-muted-foreground shadow-sm backdrop-blur" data-testid="builder-hint">
        {refMode === "move" ? "Drag the picture into place. Tap Move again when done." : refMode === "calibrate" ? (calPoints.length < 2 ? `Tap point ${calPoints.length === 0 ? "A" : "B"} on the picture.` : "Type the real distance A–B in the settings.") : TOOL_HINT[tool] ?? ""}
        {penMode && <span className="ml-1 font-medium text-foreground">Pencil mode: fingers pan and zoom.</span>}
      </div>
      {draftState.active && (draftState.tool === "polyline" || draftState.tool === "polygon" || draftState.tool === "arc") && (
        <div className="pointer-events-auto flex gap-1.5">
          <Button size="sm" variant="outline" className="h-10 bg-card" onClick={() => canvas.current?.undoPoint()}>
            <Undo2 className="mr-1 h-4 w-4" /> Undo point
          </Button>
          {draftState.tool !== "arc" && (
            <Button size="sm" className="h-10" onClick={() => canvas.current?.finish()} disabled={draftState.points < 2} data-testid="builder-finish">
              <Check className="mr-1 h-4 w-4" /> Finish
            </Button>
          )}
          <Button size="sm" variant="ghost" className="h-10 bg-card" onClick={() => canvas.current?.cancel()}>
            Cancel
          </Button>
        </div>
      )}
      {selShape?.kind === "poly" && selShape.points.length > 4 && (tool === "select" || tool === "freehand") && !draftState.active && (
        <div className="pointer-events-auto flex gap-1.5">
          <Button size="sm" variant="outline" className="h-10 bg-card" onClick={() => cleanup(false)} data-testid="builder-cleanup">
            <Wand2 className="mr-1 h-4 w-4" /> Clean up
          </Button>
          <Button size="sm" variant="outline" className="h-10 bg-card" onClick={() => cleanup(true)}>
            <Sparkles className="mr-1 h-4 w-4" /> Clean up, square corners
          </Button>
        </div>
      )}
    </div>
  );

  const shownRef = useShownReference(doc.content.sketch);
  const setReference = (r: ReferenceImage) => {
    const sk = doc.content.sketch;
    setSketch({ ...sk, references: { ...(sk.references ?? {}), [sk.plane]: r } });
  };
  // Leave the picture modes when the picture goes away or the view changes.
  useEffect(() => {
    if (!shownRef && refMode) setRefMode(null);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [shownRef, doc.content.sketch.plane]);

  const drawing = (
    <div className="relative min-h-0 min-w-0 flex-1">
      <BuilderCanvas
        ref={canvas}
        sketch={doc.content.sketch}
        onChange={(s) => setSketch(s)}
        tool={tool}
        selected={selected}
        onSelect={setSelected}
        grid={grid}
        snapPoints={snapPts}
        penMode={penMode}
        onPenDetected={() => setPenMode(true)}
        unit={unit}
        onRequestText={setTextAt}
        onDraftState={setDraftState}
        parts={doc.content.construction.method === "assembly" ? doc.content.parts : undefined}
        reference={shownRef}
        refMode={refMode}
        onReferenceChange={setReference}
        calibrationPoints={calPoints}
        onCalibrationTap={(p) => setCalPoints((pts) => (pts.length >= 2 ? [p] : [...pts, p]))}
      />
      {contextStrip}
      <div className="absolute bottom-2 right-2 flex gap-1">
        <Button variant="outline" size="icon" className="h-10 w-10 bg-card" onClick={() => canvas.current?.zoom(1 / 1.4)} aria-label="Zoom out">
          <Minus className="h-4 w-4" />
        </Button>
        <Button variant="outline" size="icon" className="h-10 w-10 bg-card" onClick={() => canvas.current?.zoom(1.4)} aria-label="Zoom in">
          <Plus className="h-4 w-4" />
        </Button>
        <Button variant="outline" size="icon" className="h-10 w-10 bg-card" onClick={() => canvas.current?.fit()} aria-label="Fit the drawing">
          <Maximize className="h-4 w-4" />
        </Button>
      </div>
      {doc.content.construction.method === "assembly" && doc.content.parts.length > 0 && doc.content.sketch.shapes.length === 0 && (
        <div className="pointer-events-none absolute inset-x-0 bottom-16 mx-auto w-fit max-w-[90%] rounded-lg border bg-card/95 px-3 py-2 text-center text-xs text-muted-foreground shadow-sm">
          Front view of the {doc.content.parts.length} parts (dashed). Edit them in the panel, or draw rectangles and add them as parts.
        </div>
      )}
    </div>
  );

  const preview = (
    <div className="relative min-h-0 min-w-0 flex-1 bg-muted/40" data-testid="builder-preview">
      {shown ? (
        <PreviewBoundary>
          <Suspense fallback={<div className="flex h-full items-center justify-center text-xs text-muted-foreground">Loading 3D preview…</div>}>
            <BuilderPreview parts={shown.parts} spec={shown.spec} color={doc.color} accentColor={doc.accentColor} finishes={doc.finishes} dark={dark} fitKey={fitKey} />
          </Suspense>
        </PreviewBoundary>
      ) : (
        <div className="flex h-full items-center justify-center p-6 text-center text-sm text-muted-foreground">
          <span>
            <Box className="mx-auto mb-2 h-8 w-8 opacity-50" />
            The 3D preview appears as soon as the drawing can be built.
          </span>
        </div>
      )}
      <div className="pointer-events-none absolute inset-x-2 top-2 flex flex-col gap-1.5">
        {size && (
          <div className="w-fit rounded-md bg-card/95 px-2 py-1 text-xs font-medium tabular-nums shadow-sm" data-testid="builder-size">
            {formatLength(size.width, unit)} W × {formatLength(size.depth, unit)} D × {formatLength(size.height, unit)} H
          </div>
        )}
        {!result.ok && (
          <div className="w-fit max-w-full rounded-md border border-warning/40 bg-card/95 px-2 py-1.5 text-xs shadow-sm" role="status" data-testid="builder-error">
            {result.error}
            {shown && <span className="block text-muted-foreground">Showing the last version that could be built.</span>}
          </div>
        )}
      </div>
      {shown && (
        <Button variant="outline" size="sm" className="absolute bottom-2 right-2 h-10 bg-card" onClick={() => setFitKey((k) => k + 1)}>
          <Maximize className="mr-1 h-4 w-4" /> Fit
        </Button>
      )}
    </div>
  );

  const panel = (
    <BuilderPanel
      doc={doc}
      commit={commit}
      setContent={setContent}
      setConstruction={setConstruction}
      setSketch={setSketch}
      unit={unit}
      selected={selected}
      setSelected={setSelected}
      selShape={selShape}
      deleteSelected={deleteSelected}
      grid={grid}
      setGrid={setGrid}
      snapPts={snapPts}
      setSnapPts={setSnapPts}
      penMode={penMode}
      setPenMode={setPenMode}
      onTemplates={() => setTemplateOpen(true)}
      artwork={
        shown && size ? (
          <ArtworkFields
            o={{ id: "builder", type: "custom", custom: shown.spec, width: size.width, depth: size.depth, height: size.height, props: {}, finishes: doc.finishes }}
            unit={unit}
            patch={(p, key) => commit({ ...doc, finishes: p.finishes as Finishes | undefined }, key)}
          />
        ) : null
      }
      reference={<ReferenceSection sketch={doc.content.sketch} setSketch={setSketch} unit={unit} mode={refMode} setMode={setRefMode} calPoints={calPoints} setCalPoints={setCalPoints} />}
    />
  );

  return (
    <div className="fixed inset-0 z-50 flex flex-col bg-background" role="dialog" aria-modal="true" aria-label="Custom Builder" data-testid="custom-builder">
      {header}
      {problem && (
        <div className="flex items-start gap-2 border-b bg-warning/12 px-4 py-2 text-sm" role="status">
          <span className="flex-1">{problem}</span>
          <Button variant="ghost" size="sm" className="h-9" onClick={() => setProblem(null)}>
            Dismiss
          </Button>
        </div>
      )}
      {restore && (
        <div className="flex flex-wrap items-center gap-2 border-b bg-info/10 px-4 py-2 text-sm" role="status">
          <span className="flex-1">You have an unsaved drawing from {new Date(restore.at).toLocaleString()}.</span>
          <Button
            size="sm"
            className="h-9"
            onClick={() => {
              setHistory(createHistory(restore.doc));
              setRestore(null);
              setFitKey((k) => k + 1);
            }}
          >
            Restore it
          </Button>
          <Button
            size="sm"
            variant="ghost"
            className="h-9"
            onClick={() => {
              clearDraft();
              setRestore(null);
            }}
          >
            Discard
          </Button>
        </div>
      )}
      {wide ? (
        <div className="flex min-h-0 flex-1">
          {toolButtons(true)}
          <div className="flex min-h-0 min-w-0 flex-1">
            {drawing}
            <div className="flex w-[38%] min-w-[260px] border-l">{preview}</div>
          </div>
          <aside className="flex w-[20rem] shrink-0 flex-col border-l bg-card" aria-label="Builder settings">
            <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain">{panel}</div>
          </aside>
        </div>
      ) : (
        <div className="flex min-h-0 flex-1 flex-col">
          {toolButtons(false)}
          <div className="flex items-center gap-2 border-b bg-card px-2 py-1.5">
            <div className="grid flex-1 grid-cols-2 gap-1 rounded-lg bg-muted p-1" role="tablist" aria-label="View">
              {(["draw", "3d"] as const).map((p) => (
                <button key={p} type="button" role="tab" aria-selected={pane === p} className={cn("h-9 rounded-md text-sm font-medium", pane === p ? "bg-background shadow-sm" : "text-muted-foreground")} onClick={() => setPane(p)} data-testid={`builder-pane-${p}`}>
                  {p === "draw" ? "Drawing" : "3D preview"}
                </button>
              ))}
            </div>
            <Button variant="outline" className="h-11" onClick={() => setPanelOpen((v) => !v)} aria-expanded={panelOpen}>
              {panelOpen ? "Hide settings" : "Settings"}
            </Button>
          </div>
          <div className="flex min-h-0 flex-1">{pane === "draw" ? drawing : preview}</div>
          {panelOpen && <div className="max-h-[42%] min-h-[9rem] shrink-0 overflow-y-auto overscroll-contain border-t bg-card pb-[env(safe-area-inset-bottom)]">{panel}</div>}
        </div>
      )}

      <TemplateDialog
        open={templateOpen}
        onOpenChange={setTemplateOpen}
        unit={unit}
        onApply={(content, meta) => {
          commit({ ...doc, content, ...(meta ?? {}) });
          setSelected(null);
          setTool("select");
          setFitKey((k) => k + 1);
          window.setTimeout(() => canvas.current?.fit(), 0);
        }}
      />
      <TextDialog
        at={textAt}
        onClose={() => setTextAt(null)}
        onSave={(text) => {
          if (!textAt) return;
          const s = doc.content.sketch;
          const label = { id: newSketchId("t"), x: textAt.x, y: textAt.y, text };
          setSketch({ ...s, labels: [...s.labels, label] });
          setSelected({ kind: "label", id: label.id });
          setTextAt(null);
        }}
      />
      <AlertDialog open={confirmClose} onOpenChange={setConfirmClose}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Close without saving?</AlertDialogTitle>
            <AlertDialogDescription>
              {request.kind === "instance" ? "Your changes to this object are not applied." : request.kind === "new" ? "Your drawing stays in this browser so you can restore it next time you open the builder." : "Your changes to this custom object are not saved."}
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel className="h-11">Keep editing</AlertDialogCancel>
            <AlertDialogAction className="h-11" onClick={onClose} data-testid="builder-discard">
              Close
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}

class PreviewBoundary extends Component<{ children: ReactNode }, { failed: boolean }> {
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  render() {
    if (this.state.failed)
      return <div className="flex h-full items-center justify-center p-6 text-center text-sm text-muted-foreground">The 3D preview isn't available on this device. The drawing and saving still work.</div>;
    return this.props.children;
  }
}

